// Writes lib/build-id.ts with the short commit SHA so the client can show
// which deploy it's running (login page "build …" stamp). Runs before every
// build and on postinstall; env-based inlining proved unreliable under
// Turbopack, a generated module always works.
import { writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

let id = (process.env.VERCEL_GIT_COMMIT_SHA || "").slice(0, 7);
if (!id) {
  try { id = execSync("git rev-parse --short HEAD").toString().trim(); }
  catch { id = "local"; }
}

writeFileSync(
  new URL("../lib/build-id.ts", import.meta.url),
  `// Generated by scripts/write-build-id.mjs — do not edit.\nexport const BUILD_ID = ${JSON.stringify(id)};\n`,
);
console.log(`[build-id] ${id}`);
